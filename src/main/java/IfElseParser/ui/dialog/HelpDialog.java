package IfElseParser.ui.dialog;

import javax.swing.*;
import java.awt.*;
import java.awt.event.KeyEvent;

public final class HelpDialog {
    private static final int PADDING = 16;
    private static final int FONT_SIZE = 16;
    private static final Dimension CONTENT_SIZE = new Dimension(740, 540);
    private static final Dimension MINIMUM_SIZE = new Dimension(480, 360);
    private static final String GUIDE = """
            <html><head><style>
            body { color: #20242b; margin: 18px; }
            h1 { font-size: 24pt; margin-top: 0; margin-bottom: 14px; }
            h2 { font-size: 18pt; margin-top: 22px; margin-bottom: 10px; }
            p { margin-top: 0; margin-bottom: 12px; }
            </style></head><body>
            <h1>Руководство пользователя</h1>
            <p>IfElseParser — текстовый редактор для учебного языкового процессора.
            Команды доступны в главном меню окна.</p>
            <p><b>Панель инструментов</b> под меню содержит кнопки создания, открытия,
            сохранения, отмены, повтора, копирования, вырезания, вставки, справки
            и информации о программе. Они выполняют те же действия, что и меню.
            В узком окне панель можно прокручивать по горизонтали.
            Кнопка <b>Пуск</b> пока недоступна.</p>

            <h2>Рабочее окно</h2>
            <p>Верхняя область предназначена для ввода и редактирования текста.
            Нижняя — для результатов работы анализатора; ввод в неё запрещён.
            Анализатор пока не реализован.</p>
            <p>Перетаскивайте разделитель между областями, чтобы изменить их размеры.
            Окно можно растягивать. Для длинного текста доступны полосы прокрутки.</p>
            <p>Над областью ввода и в заголовке окна показывается имя текущего файла
            либо <b>Новый документ</b>, если файл ещё не выбран. Полный путь к файлу
            доступен во всплывающей подсказке над его именем.</p>
            <p>Текст редактора отображается моноширинным шрифтом Noto Sans Mono.</p>

            <h2>Файл</h2>
            <p><b>Создать</b> — очищает редактор и область результатов для нового документа.
            Если есть несохранённые изменения, сначала появляется предупреждение.</p>
            <p><b>Открыть</b> — предлагает выбрать текстовый файл в кодировке UTF-8.
            После выбора проверяются несохранённые изменения текущего документа.
            При успешном открытии текст заменяется, область результатов очищается.
            Отмена выбора или ошибка чтения не удаляют текущий текст.</p>
            <p><b>Сохранить</b> — записывает текст в текущий файл в UTF-8.
            Для нового документа сначала открывается выбор имени и папки.</p>
            <p><b>Сохранить как</b> — записывает текст в выбранный файл.
            Для существующего файла запрашивается подтверждение перезаписи.
            После успешной записи последующие сохранения используют новый путь.
            Расширение не добавляется автоматически: например, укажите <b>пример.txt</b>.</p>
            <p><b>Выход</b> — закрывает приложение после проверки несохранённых изменений.
            Обычное закрытие окна выполняет ту же проверку.</p>

            <h2>Несохранённые изменения</h2>
            <p>Предупреждение появляется, если текущий текст отличается от последнего
            сохранённого состояния. Если набрать текст в новом документе и стереть его
            целиком, документ снова пуст и предупреждение не требуется.</p>
            <p><b>Сохранить</b> — сохраняет документ и продолжает выбранную команду.
            При отмене выбора файла или ошибке записи команда не продолжается.</p>
            <p><b>Не сохранять</b> — продолжает команду без записи изменений.</p>
            <p><b>Отмена</b> — возвращает к текущему документу.
            Закрытие предупреждения и клавиша <b>Escape</b> также отменяют команду.</p>

            <h2>Правка</h2>
            <p>Команды этого меню работают с верхней областью редактирования.</p>
            <p><b>Отменить</b> — отменяет последнее изменение текста.
            При обычном наборе символы отменяются по одному.</p>
            <p><b>Повторить</b> — возвращает последнее отменённое изменение.
            Например: после ввода «абв» отмена оставит «аб», а повтор вернёт «абв».
            Новый ввод после отмены удаляет возможность повторить прежнее изменение.</p>
            <p>Пункты отмены и повтора недоступны, если соответствующих действий нет.
            Создание и открытие документа сбрасывают историю; сохранение её не сбрасывает.</p>
            <p><b>Вырезать</b> — переносит выделенный текст в буфер обмена,
            удаляя его из редактора.</p>
            <p><b>Копировать</b> — помещает выделенный текст в буфер обмена,
            оставляя его в редакторе.</p>
            <p><b>Вставить</b> — вставляет текст из буфера обмена в позицию курсора.
            Если есть выделение, заменяет его вставляемым текстом.</p>
            <p><b>Удалить</b> — удаляет выделенный фрагмент без копирования в буфер.
            Без выделения эта команда ничего не меняет.</p>
            <p><b>Выделить всё</b> — выделяет весь текст редактора.</p>

            <h2>Справка</h2>
            <p><b>Вызов справки</b> — открывает это руководство. Прокручивайте текст
            колёсиком мыши или полосой прокрутки; размер окна можно менять.</p>
            <p><b>О программе</b> — показывает название и назначение приложения.</p>
            <p>Закройте справку кнопкой <b>Закрыть</b>, клавишей <b>Escape</b>
            или обычной командой закрытия окна, чтобы вернуться к редактору.</p>

            <h2>Пока не реализовано</h2>
            <p>Команда <b>Пуск</b> зарезервирована для следующего этапа и пока недоступна.
            Пункты меню <b>Текст</b> открывают справочные окна с материалами будущего
            языкового процессора. Отмена и повтор доступны также по сочетаниям
            <b>Ctrl+Z</b> и <b>Ctrl+Y</b>.</p>
            </body></html>
            """;

    private HelpDialog() {
    }

    public static void show(JFrame owner) {
        JDialog dialog = new JDialog(owner, "Руководство пользователя", true);
        dialog.setDefaultCloseOperation(WindowConstants.DISPOSE_ON_CLOSE);

        JEditorPane text = new JEditorPane();
        text.putClientProperty(JEditorPane.HONOR_DISPLAY_PROPERTIES, true);
        text.setContentType("text/html");
        text.setFont(new Font("Noto Sans", Font.PLAIN, FONT_SIZE));
        text.setEditable(false);
        text.setText(GUIDE);
        text.setCaretPosition(0);
        text.getAccessibleContext().setAccessibleName("Руководство пользователя");
        JScrollPane scroll = new JScrollPane(text);
        scroll.setPreferredSize(CONTENT_SIZE);

        JPanel content = new JPanel(new BorderLayout(0, PADDING));
        content.setBorder(BorderFactory.createEmptyBorder(PADDING, PADDING, PADDING, PADDING));
        content.add(scroll, BorderLayout.CENTER);
        JButton closeButton = EditorDialogs.createButton("Закрыть");
        closeButton.addActionListener(event -> dialog.dispose());
        JPanel buttons = new JPanel(new FlowLayout(FlowLayout.TRAILING, 0, 0));
        buttons.add(closeButton);
        content.add(buttons, BorderLayout.SOUTH);
        dialog.setContentPane(content);
        dialog.getRootPane().setDefaultButton(closeButton);
        dialog.getRootPane().registerKeyboardAction(event -> dialog.dispose(),
                KeyStroke.getKeyStroke(KeyEvent.VK_ESCAPE, 0), JComponent.WHEN_IN_FOCUSED_WINDOW);
        dialog.setMinimumSize(MINIMUM_SIZE);
        dialog.pack();
        dialog.setLocationRelativeTo(owner);
        dialog.setVisible(true);
    }
}
